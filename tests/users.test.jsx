import { it, expect, vi } from 'vitest';
import { render, screen, fireEvent, waitFor } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import UsersPage from '../src/pages/UsersPage';
import { getUsers, createUser, updateUserPassword } from '../src/api/users';
vi.mock('../src/api/users', () => ({ getUsers: vi.fn(), createUser: vi.fn(), updateUserPassword: vi.fn(), deleteUser: vi.fn(), getRetiredUsers: vi.fn(), restoreUser: vi.fn() }));
it('masks the initial password and prevents duplicate creation while pending', async () => {
  getUsers.mockResolvedValue({ data: [] });
  let finish;
  createUser.mockImplementation(() => new Promise((resolve) => { finish = resolve; }));
  render(<UsersPage />);
  await screen.findByText('조회된 사용자가 없습니다.');
  await userEvent.type(screen.getByLabelText('사원번호'), '1001');
  await userEvent.type(screen.getByLabelText('이름'), '홍길동');
  const password = screen.getByLabelText('초기 비밀번호');
  expect(password).toHaveAttribute('type','password');
  await userEvent.type(password, 'long-password');
  const form = password.closest('form');
  fireEvent.submit(form); fireEvent.submit(form);
  expect(createUser).toHaveBeenCalledOnce();
  expect(screen.getByRole('button', { name: '생성 중…' })).toBeDisabled();
  finish({ success: true });
  await screen.findByText('기사가 추가되었습니다.');
  expect(password).toHaveValue('');
});
it('requires matching password confirmation and displays API failures inside the modal', async () => {
  getUsers.mockResolvedValue({ data: [{ employeeId: '1001', name: '홍길동', role: 'DRIVER' }] });
  updateUserPassword.mockRejectedValue(new Error('변경 실패'));
  render(<UsersPage />);
  await userEvent.click(await screen.findByRole('button', { name: '비밀번호 변경' }));
  await userEvent.type(screen.getByLabelText('새 비밀번호'), 'long-password');
  await userEvent.type(screen.getByLabelText('새 비밀번호 확인'), 'different-password');
  const buttons = screen.getAllByRole('button', { name: '비밀번호 변경' });
  await userEvent.click(buttons.at(-1));
  expect(await screen.findByRole('alert')).toHaveTextContent('일치하지 않습니다');
  expect(updateUserPassword).not.toHaveBeenCalled();
  await userEvent.clear(screen.getByLabelText('새 비밀번호 확인'));
  await userEvent.type(screen.getByLabelText('새 비밀번호 확인'), 'long-password');
  await userEvent.click(buttons.at(-1));
  await waitFor(() => expect(screen.getByRole('dialog')).toHaveTextContent('변경 실패'));
});
